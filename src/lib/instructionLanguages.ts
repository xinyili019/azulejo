export function instructionLocale(direction: string): InstructionLocale {
  if (direction.includes("zh-hans")) return "zhHans";
  if (direction.includes("zh-hant")) return "zhHant";
  const code = direction.split("-")[1];
  return ["fr", "es", "bn", "ar", "hi", "ur", "uk", "ne", "fa", "ru", "it"].includes(code) ? code as InstructionLocale : "en";
}

export function translateInstruction(text: string, locale: InstructionLocale): string {
  const dictionary = translations[locale] ?? learningTranslations[locale];
  if (!dictionary) return text;
  if (dictionary[text]) return dictionary[text];
  if (dictionary[text.toLowerCase()]) return dictionary[text.toLowerCase()];
  for (const [source, target] of Object.entries(dictionary)) {
    if (!source.includes("{0}")) continue;
    const pattern = source.split(/(\{\d+\})/).map(part => /^\{\d+\}$/.test(part) ? "(.+?)" : part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("");
    const match = text.match(new RegExp(`^${pattern}$`));
    if (match) return target.replace(/\{(\d+)\}/g, (_, index) => match[Number(index) + 1]);
  }
  return text;
}

// Localize structured UI copy, including messages produced by format functions.
export function translateCopy<T>(value: T, locale: InstructionLocale): T {
  if (typeof value === "string") return translateInstruction(value, locale) as T;
  if (typeof value === "function") return ((...args: unknown[]) => translateCopy(value(...args), locale)) as T;
  if (Array.isArray(value)) return value.map(item => translateCopy(item, locale)) as T;
  if (value && typeof value === "object") return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, key === "locale" ? item : translateCopy(item, locale)])) as T;
  return value;
}
